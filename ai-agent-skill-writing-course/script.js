function showOnly(id) {
  ["welcome", "lesson-view", "sources-view", "review-view"].forEach((viewId) => {
    $(viewId).classList.toggle("hidden", viewId !== id);
  });
  $("sidebar").classList.remove("open");
}

function saveDone() {
  localStorage.setItem("skillCourseDone", JSON.stringify([...done]));
  updateProgress();
}

function resetProgress() {
  done.clear();
  active = 0;
  localStorage.removeItem("skillCourseDone");
  renderNav();
  updateProgress();
  showOnly("welcome");
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function updateProgress() {
  const count = done.size;
  $("progress-text").textContent = `${count} / ${course.lessons.length} уроков`;
  $("progress-fill").style.width = `${Math.round((count / course.lessons.length) * 100)}%`;
  $("btn-review").disabled = count < course.lessons.length;
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, (char) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    "\"": "&quot;",
    "'": "&#039;"
  })[char]);
}
