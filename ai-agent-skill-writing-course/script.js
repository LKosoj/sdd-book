let course = COURSE_DATA;
let active = 0;
const done = new Set(JSON.parse(localStorage.getItem("skillCourseDone") || "[]"));
const $ = (id) => document.getElementById(id);

init();

function init() {
  $("course-title").textContent = course.title;
  $("course-description").textContent = course.description;
  renderNav();
  renderSources();
  renderChecklist();
  updateProgress();

  $("btn-start").onclick = () => showLesson(0);
  $("btn-sources").onclick = showSources;
  $("btn-welcome-sources").onclick = showSources;
  $("btn-review").onclick = showReview;
  $("btn-prev").onclick = () => showLesson(Math.max(0, active - 1));
  $("btn-next").onclick = completeCurrentLesson;
  $("sidebar-toggle").onclick = () => $("sidebar").classList.toggle("open");
}

function renderNav() {
  const nav = $("lesson-nav");
  nav.innerHTML = "";

  course.lessons.forEach((lesson, index) => {
    const button = document.createElement("button");
    button.className = "lesson-nav-item" + (index === active ? " active" : "") + (done.has(index) ? " completed" : "");
    button.innerHTML = `
      <span class="nav-icon">${done.has(index) ? "✓" : index + 1}</span>
      <span>${escapeHtml(lesson.title)}</span>
    `;
    button.onclick = () => showLesson(index);
    nav.appendChild(button);
  });
}

function showLesson(index) {
  active = index;
  showOnly("lesson-view");

  const lesson = course.lessons[index];
  $("lesson-badge").textContent = `Урок ${index + 1} из ${course.lessons.length}`;
  $("lesson-title").textContent = lesson.title;
  $("lesson-subtitle").textContent = lesson.subtitle;
  $("lesson-goal").textContent = lesson.goal;
  $("objectives-list").innerHTML = lesson.objectives.map((item) => `<li>${escapeHtml(item)}</li>`).join("");
  $("concepts").innerHTML = lesson.concepts.map((item) => `<p class="concept-card">${escapeHtml(item)}</p>`).join("");
  $("example-text").textContent = lesson.example;
  $("practice-text").textContent = lesson.practice;
  $("flashcards").innerHTML = lesson.flashcards.map(([front, back]) => `
    <div class="flashcard" tabindex="0">
      <div class="flashcard-inner">
        <div class="flashcard-front">${escapeHtml(front)}</div>
        <div class="flashcard-back">${escapeHtml(back)}</div>
      </div>
    </div>
  `).join("");

  document.querySelectorAll(".flashcard").forEach((card) => {
    card.onclick = () => card.classList.toggle("flipped");
    card.onkeydown = (event) => {
      if (event.key === "Enter" || event.key === " ") {
        event.preventDefault();
        card.classList.toggle("flipped");
      }
    };
  });

  renderQuiz(lesson.quiz);
  renderLessonSources(lesson.sources);
  $("btn-prev").disabled = index === 0;
  $("btn-next").textContent = index === course.lessons.length - 1 ? "Завершить курс" : "Далее ->";
  renderNav();
  updateProgress();
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function renderQuiz(quiz) {
  renderQuestionSet("quiz", quiz);
}

function renderFinalQuiz() {
  $("review-result").classList.add("hidden");
  renderQuestionSet("final-quiz", FINAL_QUIZ, (score, total) => {
    const percent = Math.round((score / total) * 100);
    $("review-result").classList.remove("hidden");
    $("review-score").textContent = `${score} / ${total} (${percent}%)`;
    $("review-message").textContent = percent >= 80
      ? "Отличный результат. Можно переходить к практическому зачёту."
      : percent >= 50
        ? "База есть. Повторите уроки, где были ошибки, и проверьте skill ещё раз."
        : "Лучше пройти курс повторно и собрать capstone после второго прохода.";
  });
}

function renderQuestionSet(containerId, questions, onComplete) {
  const answers = new Map();
  const container = $(containerId);
  container.innerHTML = questions.map((question, questionIndex) => `
    <div class="quiz-item" data-question="${questionIndex}">
      <div class="quiz-question">${questionIndex + 1}. ${escapeHtml(question.q)}</div>
      ${question.options.map((option, optionIndex) => `<button class="quiz-option" data-question="${questionIndex}" data-index="${optionIndex}">${escapeHtml(option)}</button>`).join("")}
      <div class="quiz-feedback"></div>
    </div>
  `).join("");

  container.querySelectorAll(".quiz-option").forEach((button) => {
    button.onclick = () => {
      const questionIndex = Number(button.dataset.question);
      if (answers.has(questionIndex)) return;

      const question = questions[questionIndex];
      const selected = Number(button.dataset.index);
      const item = button.closest(".quiz-item");
      item.querySelectorAll(".quiz-option").forEach((option, index) => {
        option.disabled = true;
        if (index === question.answer) option.classList.add("correct");
      });
      if (selected !== question.answer) button.classList.add("wrong");

      const feedback = item.querySelector(".quiz-feedback");
      feedback.textContent = question.explain;
      feedback.classList.add("visible");
      answers.set(questionIndex, selected);

      if (onComplete && answers.size === questions.length) {
        const score = [...answers].filter(([index, answer]) => answer === questions[index].answer).length;
        onComplete(score, questions.length);
      }
    };
  });
}

function renderLessonSources(ids) {
  $("lesson-sources").innerHTML = ids.map((index) => sourceCard(course.sources[index])).join("");
}

function renderSources() {
  $("all-sources").innerHTML = course.sources.map(sourceCard).join("");
}

function sourceCard(source) {
  return `
    <a class="source-card" href="${source.url}" target="_blank" rel="noopener">
      <div class="source-title">${escapeHtml(source.title)}</div>
      <div class="source-note">${escapeHtml(source.note)}</div>
    </a>
  `;
}

